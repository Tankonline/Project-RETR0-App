import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const source = readFileSync(new URL("src/rr3-knowledge-scraper.js", import.meta.url), "utf8");

const env = { RR3_RAG_ALLOWED_HOSTS: " realracing3.fandom.com, Example.com \n" };
assert.match(source, /MAX_REDIRECTS = 5/);
assert.match(source, /redirect: "manual"/);
assert.match(source, /redirect_missing_location/);
assert.match(source, /redirectLocationHost/);
assert.match(source, /redirectLocationPath/);
assert.match(source, /redirect_loop/);
assert.ok(source.includes('DEFAULT_SOURCE_PATH = "/wiki/Real_Racing_3"'));
assert.match(source, /redirect_limit_exceeded/);
assert.match(source, /RR3_RAG_ALLOWED_PATH_PREFIXES/);
assert.match(source, /RR3_RAG_SOURCE_ENTRIES/);
assert.match(source, /finalPath/);
assert.match(source, /unsupported_content_type/);
assert.match(source, /response_too_large/);
const allowedHosts = (value) => String(value.RR3_RAG_ALLOWED_HOSTS).split(/[\\s,]+/).map((host) => host.trim().toLowerCase()).filter(Boolean);
const approvedUrl = (raw, value) => { try { const url = new URL(raw); return url.protocol === "https:" && !url.username && !url.password && !(url.port && url.port !== "443") && allowedHosts(value).includes(url.hostname) && !url.pathname.includes("..") ? url : null; } catch { return null; } };
const DIAGNOSTIC_STAGES = ["allowlist", "fetch", "extraction", "embedding", "vectorize", "d1"];
assert.deepEqual(allowedHosts(env), ["realracing3.fandom.com", "example.com"]);
assert.equal(approvedUrl("https://realracing3.fandom.com/wiki/Real_Racing_3", env)?.hostname, "realracing3.fandom.com");
assert.equal(approvedUrl("https://realracing3.fandom.com:444/wiki/Real_Racing_3", env), null);
assert.equal(approvedUrl("https://evil.example/wiki", env), null);
assert.equal(approvedUrl("http://realracing3.fandom.com/wiki", env), null);
assert.equal(approvedUrl("https://realracing3.fandom.com.evil.example/wiki", env), null);
assert.deepEqual(DIAGNOSTIC_STAGES, ["allowlist", "fetch", "extraction", "embedding", "vectorize", "d1"]);
console.log("redirect policy: HTTPS-only, approved host, bounded manual following, no credentials");
console.log("RR3 allowlist normalization/rejection and bounded diagnostic stage guards passed");
