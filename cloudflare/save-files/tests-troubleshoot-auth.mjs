import assert from "node:assert/strict";
import { readFileSync, statSync } from "node:fs";

const source = readFileSync(new URL("src/save-files-worker.js", import.meta.url), "utf8");
const route = source.indexOf('if (url.pathname === "/troubleshoot" && method === "POST")');
assert.ok(route >= 0, "troubleshoot route must exist");
const legacyGate = source.indexOf('const authenticated = !env.AUTH_KEY');
assert.ok(legacyGate >= 0, "legacy AUTH_KEY guard must remain only for legacy root routes");
const routeText = source.slice(route, route + 2200);
assert.ok(routeText.includes("request.arrayBuffer"), "route must read exact body bytes");
assert.ok(routeText.includes("authenticate(request, env.SKINS_DB, url, bodyBytes)"), "route must use installation authentication");
assert.ok(routeText.includes("identity.status"), "route must reject invalid signatures safely");
assert.ok(routeText.includes('{ error: "Unauthorized", code: identity.code, requestId, route: "installation-auth-v2", deployment: deploymentMarker }'), "auth errors must be structured and bounded");
assert.ok(routeText.includes('"X-RETR0-Troubleshoot-Route"'), "route headers must be deterministic on auth errors");
assert.ok(routeText.includes('"X-RETR0-Deployment"'), "deployment header must be deterministic on auth errors");
assert.ok(!routeText.includes("identity.installationId"), "auth rejection must not expose installation ID");
assert.ok(!routeText.includes("X-Signature"), "auth rejection must not expose signature");
assert.ok(!routeText.includes("X-RETR0-KEY"), "route must not use legacy shared key");
assert.ok(routeText.indexOf("identity = await authenticate") < routeText.indexOf("const requestBody = parseJson"), "auth must precede body parsing");
for (const marker of ["timestamp", "nonce_reused", "${url.pathname}${url.search}"]) assert.ok(source.includes(marker), `signature invariant missing: ${marker}`);

const marker = "installation-auth-v2";
const deploymentMarker = "retr0-troubleshoot-installation-auth-v2-20261105";
assert.ok(source.includes(marker), "source must contain the production route marker");
assert.ok(source.includes(deploymentMarker), "source must contain the deterministic deployment marker");
const rootGateSection = source.slice(legacyGate, source.indexOf("if (url.pathname === \"/manifest\"", legacyGate));
assert.ok(source.includes('if (!authenticated && !(url.pathname === "/troubleshoot" && method === "POST"))'), "legacy gate must explicitly exclude /troubleshoot");
assert.ok(!source.includes('if (url.pathname === "/troubleshoot" && method === "POST") {\n        const authenticated'), "source must not contain a legacy body-only troubleshoot branch");

const bundlePath = ".wrangler-dry-run/production/save-files-worker.js";
const bundleUrl = new URL(bundlePath, import.meta.url);
assert.ok(readFileSync(bundleUrl, { flag: "r" }), `${bundlePath}: expected production dry-run bundle is absent`);
const bundle = readFileSync(bundleUrl, "utf8");
const sourceMtime = statSync(new URL("src/save-files-worker.js", import.meta.url)).mtimeMs;
const bundleMtime = statSync(bundleUrl).mtimeMs;
assert.ok(bundleMtime >= sourceMtime, `${bundlePath}: bundle is stale; regenerate with Wrangler production dry-run`);
const bundleRoute = bundle.indexOf('if (url.pathname === "/troubleshoot" && method === "POST")');
assert.ok(bundleRoute >= 0, `${bundlePath}: installation-auth route must exist in generated bundle`);
const bundleRouteEnd = bundle.indexOf('if (url.pathname === "/like"', bundleRoute);
const text = bundle.slice(bundleRoute, bundleRouteEnd > bundleRoute ? bundleRouteEnd : bundleRoute + 3000);
assert.ok(text.includes("authenticate(request, env.SKINS_DB, url, bodyBytes)"), `${bundlePath}: installation authentication is missing from route`);
assert.ok(text.includes(marker), `${bundlePath}: production route marker is missing`);
assert.ok(text.includes('"X-RETR0-Troubleshoot-Route"'), `${bundlePath}: diagnostic route header is missing`);
assert.ok(text.includes('"X-RETR0-Deployment"'), `${bundlePath}: deployment marker header is missing`);
assert.ok(bundle.includes(deploymentMarker), `${bundlePath}: deterministic deployment marker is missing`);
assert.ok(text.includes('"@cf/ibm-granite/granite-4.0-h-micro"'), `${bundlePath}: Granite model is missing`);
assert.ok(!text.includes("@cf/meta/llama-3.2-3b-instruct"), `${bundlePath}: legacy Llama model remains`);
assert.ok(!text.includes("const authenticated = !env.AUTH_KEY"), `${bundlePath}: legacy body-only /troubleshoot handler remains`);
assert.ok(!text.includes("request.json()"), `${bundlePath}: legacy body-only route remains`);
const bundleGate = bundle.indexOf('if (!authenticated && !(url.pathname === "/troubleshoot" && method === "POST"))');
assert.ok(bundleGate >= 0, `${bundlePath}: legacy gate must explicitly exclude /troubleshoot`);
assert.ok(bundleRoute > bundleGate, `${bundlePath}: troubleshoot handler must be after the legacy gate condition while excluded from its return`);
assert.ok(!text.includes('textResponse("Unauthorized", 401)'), `${bundlePath}: legacy plain-text Unauthorized remains in route`);
console.log("troubleshoot installation-auth and generated-bundle guards passed");
